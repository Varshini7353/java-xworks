class Bicycle {

    public static void main(String[] args) {
        getBrand();
        getType();
        getFrameMaterial();
        getPrice();
        getGearCount();
    }

    public static void getBrand() {
        System.out.println("The brand of the bicycle is: Hero");
    }

    public static void getType() {
        System.out.println("The type is: Mountain Bike");
    }

    public static void getFrameMaterial() {
        System.out.println("The frame material is: Steel");
    }

    public static void getPrice() {
        System.out.println("The price of the bicycle is: ₹18,999");
    }

    public static void getGearCount() {
        System.out.println("The number of gears is: 21");
    }

}