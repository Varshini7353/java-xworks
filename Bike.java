class Bike {

    public static void main(String[] args) {
        getBrand();
        getEngineCapacity();
        getMileage();
        getPrice();
        getColor();
    }

    public static void getBrand() {
        System.out.println("The brand of the bike is: Honda");
    }

    public static void getEngineCapacity() {
        System.out.println("The engine capacity is: 160 cc");
    }

    public static void getMileage() {
        System.out.println("The mileage is: 55 km/l");
    }

    public static void getPrice() {
        System.out.println("The price of the bike is: ₹1,35,000");
    }

    public static void getColor() {
        System.out.println("The color of the bike is: Red");
    }
}