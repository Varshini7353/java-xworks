class Backpack {

    public static void main(String[] args) {

        getBrand();
        getCapacity();
        getMaterial();
        getPrice();
        getColor();

    }

    public static void getBrand() {
        System.out.println("The brand of the backpack is: Wildcraft");
    }

    public static void getCapacity() {
        System.out.println("The capacity is: 35 Litres");
    }

    public static void getMaterial() {
        System.out.println("The material is: Polyester");
    }

    public static void getPrice() {
        System.out.println("The price of the backpack is: ₹2,499");
    }

    public static void getColor() {
        System.out.println("The color of the backpack is: Blue");
    }

}